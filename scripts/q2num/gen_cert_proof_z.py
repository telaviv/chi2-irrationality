"""Write `Chi2Irrational/QZ/Cert{Name}.lean` (kernel checks of `QZ/CertData{Name}.lean`), in the format of `Cert/Q6.lean`.

Usage: python scripts/q2num/gen_cert_proof_z.py Name nCells chunk targetNum targetDen "gen args" "PhiQ decimal"
  e.g. python scripts/q2num/gen_cert_proof_z.py Q177 800 50 4005 1000 "2 177 800 8 70 1 1" "-4.0067932"
Cells are checked in chunks; the chunks are combined by a balanced tree of `cellsOK_append` (no long case split).
"""
import sys

name = sys.argv[1]
n, ch, tn, td = (int(a) for a in sys.argv[2:6])
gen, phid = sys.argv[6], sys.argv[7]
nch = (n + ch - 1) // ch
T = f"-{tn} / {td}"
o = []
o.append(f"""/-
# The dual certificate at `w = (a/q)²` ({name}): kernel checks

Every check of `CDataZ.Valid` for `CertData{name}.data` by `decide +kernel`; the certified exponent
`Φ ≤ PhiQ ≤ {T}` (`PhiQ = {phid}…`). Theorem B (`DualCertW.analyticZ`) then bounds `|Δ_h(χ₂(1/ζ); ζ)|`, `ζ = q/a`.
Data generated by `scripts/q2num/gen_cert_z.py {gen}` (untrusted; every number is re-checked by the kernel).
File generated by `scripts/q2num/gen_cert_proof_z.py`.
-/
import Chi2Irrational.QZ.CertData{name}

namespace Chi2Irr.QZ.Cert.{name}

open Chi2Irr.Cert Chi2Irr.QZ CDataZ

lemma tabOK : checkTab data.tab 1 = true := by decide +kernel
""")
chunks = []
for i in range(nch):
    lo = i * ch; m = min(ch, n - lo)
    chunks.append((lo, m, f"cells{i}"))
    o.append(f"lemma cells{i} : data.cellsOK {lo} {m} = true := by decide +kernel\n")

# balanced combination tree
level = 0
cur = chunks
while len(cur) > 1:
    nxt = []
    for j in range(0, len(cur), 2):
        if j + 1 < len(cur):
            (lo1, m1, n1), (lo2, m2, n2) = cur[j], cur[j + 1]
            nm = f"comb{level}_{j // 2}"
            o.append(f"lemma {nm} : data.cellsOK {lo1} {m1 + m2} = true := cellsOK_append {lo1} {m1} {m2} {n1} {n2}\n")
            nxt.append((lo1, m1 + m2, nm))
        else:
            nxt.append(cur[j])
    cur = nxt
    level += 1
top = cur[0][2]
assert cur[0][0] == 0 and cur[0][1] == n
o.append(f"""lemma cellsAll : data.cellsOK 0 {n} = true := {top}

lemma EOK : data.EOK = true := by decide +kernel

lemma tailOK : data.tailOK = true := by decide +kernel

theorem valid : data.Valid where
  a1 := by decide
  aq := by decide
  L1 := by decide
  X1 := by decide
  NX := by decide
  Ks := by decide
  len := by decide +kernel
  slen := by decide +kernel
  crange := by decide +kernel
  mass := by decide +kernel
  tab := tabOK
  cells := fun k hk => data.cells_of 0 {n} cellsAll k (Nat.zero_le k)
    (by rw [show data.X * data.L = {n} from rfl] at hk; omega)
  tail := tailOK
  E := EOK

lemma phiQ_le : data.PhiQ ≤ {T} := by decide +kernel

/-- The {name} dual certificate, with `Φ ≤ {T}`. -/
theorem phi_le : (toCertZ valid).Phi ≤ {T} := by
  have h1 := Phi_le valid
  have h2 : (data.PhiQ : ℝ) ≤ {T} := by exact_mod_cast phiQ_le
  linarith

end Chi2Irr.QZ.Cert.{name}
""")
open(f"Chi2Irrational/QZ/Cert{name}.lean", "w", encoding="utf-8", newline="\n").write("\n".join(o))
