"""Write `Chi2Irrational/Cert/Q{q}.lean` (kernel checks of `DataQ{q}.data`), in the format of `Cert/Q14.lean`.

Usage: python scripts/q/gen_cert_proof.py q nCells chunk targetNum targetDen "gen args" "PhiQ decimal"
"""
import sys

q, n, ch, tn, td = (int(a) for a in sys.argv[1:6])
gen, phid = sys.argv[6], sys.argv[7]
nch = (n + ch - 1) // ch
T = f"-{tn} / {td}"
o = []
o.append(f"""/-
# The dual certificate for q = {q}: kernel checks

Every check of `CData.Valid` for `DataQ{q}.data` by `decide +kernel`; the certified exponent
`Φ ≤ PhiQ ≤ {T}` (`PhiQ = {phid}…`). Theorem B then gives `|Δ_h(χ₂(1/{q}))| ≤ exp((Φ + ε) h²)` eventually.
Data generated by `scripts/gen_cert.py {gen}` (untrusted; every number is re-checked by the kernel).
File generated by `scripts/q/gen_cert_proof.py`.
-/
import Chi2Irrational.Cert.DataQ{q}

namespace Chi2Irr.Cert.Q{q}

open Chi2Irr.Cert CData

lemma tabOK : checkTab data.tab 1 = true := by decide +kernel
""")
for i in range(nch):
    lo = i * ch; m = min(ch, n - lo)
    o.append(f"lemma cells{i} : data.cellsOK {lo} {m} = true := by decide +kernel\n")
o.append("""lemma EOK : data.EOK = true := by decide +kernel

lemma tailOK : data.tailOK = true := by decide +kernel

theorem valid : data.Valid where
  q2 := by decide
  L1 := by decide
  X1 := by decide
  NX := by decide
  Ks := by decide
  len := by decide +kernel
  slen := by decide +kernel
  crange := by decide +kernel
  mass := by decide +kernel
  tab := tabOK
  cells := fun k hk => by""")
o.append(f"    have hk' : k < {n} := hk")
for i in range(nch):
    lo = i * ch; m = min(ch, n - lo)
    lower = "(by omega)" if i == 0 else f"h{i-1}"
    if i < nch - 1:
        o.append(f"    rcases lt_or_ge k {lo + m} with h{i} | h{i}")
        o.append(f"    · exact data.cells_of {lo} {m} cells{i} k {lower} (by omega)")
    else:
        o.append(f"    · exact data.cells_of {lo} {m} cells{i} k {lower} (by omega)")
o.append(f"""  tail := tailOK
  E := EOK

lemma phiQ_le : data.PhiQ ≤ {T} := by decide +kernel

/-- The `q = {q}` dual certificate, with `Φ ≤ {T}`. -/
theorem phi_le : (toCert valid).Phi ≤ {T} := by
  have h1 := Phi_le valid
  have h2 : (data.PhiQ : ℝ) ≤ {T} := by exact_mod_cast phiQ_le
  linarith

end Chi2Irr.Cert.Q{q}
""")
open(f"Chi2Irrational/Cert/Q{q}.lean", "w", encoding="utf-8", newline="\n").write("\n".join(o))
